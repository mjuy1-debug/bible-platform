// 헬퍼: 퀴즈 세트 객체로부터 정확한 바이블프로젝트 영상 정보 조회
export function getBibleProjectVideo(quiz) {
  if (!quiz) return null;

  // 1. 인물 퀴즈 ID 직접 매칭
  if (BIBLE_PROJECT_VIDEOS[quiz.id]) {
    const item = BIBLE_PROJECT_VIDEOS[quiz.id];
    return {
      ...item,
      embeddable: true
    };
  }

  // 2. 인물 카테고리인 경우 제목에서 인물명 매칭
  if (quiz.category === '👑 성경 인물 열전') {
    const rawName = quiz.roundTitle.replace(/^\[.*?\]\s*/, '').trim();
    const found = Object.values(BIBLE_PROJECT_VIDEOS).find(v => 
      rawName.includes(v.characterName) || v.characterName.includes(rawName)
    );
    if (found) {
      return {
        ...found,
        embeddable: true
      };
    }
  }

  // 3. 성경 책 이름(bookName) 매핑
  if (quiz.bookName && BIBLE_BOOK_VIDEOS[quiz.bookName]) {
    const book = BIBLE_BOOK_VIDEOS[quiz.bookName];
    return {
      characterName: '',
      title: `바이블프로젝트: ${book.title}`,
      videoId: book.videoId,
      youtubeUrl: `https://www.youtube.com/watch?v=${book.videoId}`,
      bibleProjectUrl: book.bpUrl,
      description: `${quiz.bookName}의 구속사적 맥락과 전체 구조를 애니메이션으로 깊이 있게 조명합니다.`,
      duration: '약 7~9분',
      channel: '바이블프로젝트 (BibleProject - Korean)',
      embeddable: true
    };
  }

  // 4. 폴백: 기본 바이블프로젝트 대표 영상 (창세기 1-11장 개요)
  const defaultVideoId = 'kYJv4032m-U';
  return {
    characterName: '',
    title: quiz.roundTitle || '바이블프로젝트 말씀 영상',
    videoId: defaultVideoId,
    youtubeUrl: `https://www.youtube.com/watch?v=${defaultVideoId}`,
    bibleProjectUrl: 'https://bibleproject.com/korean/',
    description: '바이블프로젝트 공식 채널의 고품질 애니메이션을 통해 말씀의 깊은 은혜를 누려보세요.',
    duration: '약 8분',
    channel: '바이블프로젝트 (BibleProject - Korean)',
    embeddable: true
  };
}
