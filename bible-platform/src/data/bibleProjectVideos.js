// 헬퍼: 퀴즈 세트 ID 또는 카테고리/인물명으로 비디오 정보 조회
export function getBibleProjectVideo(quiz) {
  if (!quiz) return null;

  // 1. 직접 매핑된 ID 체크
  if (BIBLE_PROJECT_VIDEOS[quiz.id]) {
    return BIBLE_PROJECT_VIDEOS[quiz.id];
  }

  // 2. 성경 인물 카테고리인 경우 제목에서 인물명 추출 매칭
  if (quiz.category === '👑 성경 인물 열전') {
    const rawName = quiz.roundTitle.replace(/^\[.*?\]\s*/, '').trim();
    const found = Object.values(BIBLE_PROJECT_VIDEOS).find(v => 
      rawName.includes(v.characterName) || v.characterName.includes(rawName)
    );
    if (found) return found;

    // 기본 바이블프로젝트 검색 정보 생성
    return {
      characterName: rawName,
      title: `${rawName} 말씀 개요`,
      videoId: null,
      searchQuery: `바이블프로젝트 ${rawName}`,
      description: `바이블프로젝트의 고품질 애니메이션으로 ${rawName}의 신앙과 구속사적 의미를 시청해보세요.`,
      duration: '약 5~8분',
      channel: '바이블프로젝트'
    };
  }

  // 3. 책 이름 기반 매핑
  if (quiz.bookName) {
    const bookDef = BOOK_DEFAULT_VIDEOS[quiz.bookName];
    return {
      characterName: '',
      title: `바이블프로젝트: ${bookDef ? bookDef.title : `${quiz.bookName} 개요`}`,
      videoId: bookDef ? bookDef.videoId : null,
      searchQuery: `바이블프로젝트 ${quiz.bookName} 개요`,
      description: `${quiz.bookName}의 전체 구조와 핵심 메시지를 애니메이션으로 한눈에 정리합니다.`,
      duration: '약 7~9분',
      channel: '바이블프로젝트'
    };
  }

  return null;
}
