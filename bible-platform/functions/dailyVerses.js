/**
 * 오늘 날짜 기반으로 말씀 반환 (KST 기준)
 */
function getTodayVerse(kstDate) {
  const date = kstDate || new Date();
  const dayOfYear = Math.floor(
    (date - new Date(date.getFullYear(), 0, 0)) / (1000 * 60 * 60 * 24)
  );
  const idx = (dayOfYear - 1 + baseVerses.length) % baseVerses.length;
  return baseVerses[idx];
}

